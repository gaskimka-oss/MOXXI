def normalize_gender(raw: str | None) -> str:
    """Нормализует пол: 'female', 'male', или 'none'."""
    if not raw:
        return "none"
    s = str(raw).strip().lower()
    if s in {"ж", "female", "girl", "f", "женщина", "девушка", "девочка"}:
        return "female"
    if s in {"м", "male", "boy", "m", "мужчина", "парень", "мальчик"}:
        return "male"
    if any(k in s for k in ["дев", "жен", "female", "girl", "тян", "девушк", "девочк", "женщин", "леди", "lady"]):
        return "female"
    if any(k in s for k in ["пар", "муж", "male", "boy", "кун", "парен", "мальчик", "мужчин", "пацан"]):
        return "male"
    return "none"


async def get_user_gender(user_id: int) -> str:
    """Получает пол пользователя (female / male / none)."""
    if not user_id:
        return "none"
    try:
        # 1. Проверяем таблицу users
        urow = await db.fetchone("SELECT gender FROM users WHERE user_id=?", (user_id,))
        if urow and urow.get("gender"):
            g = normalize_gender(urow["gender"])
            if g != "none":
                return g

        # 2. Проверяем таблицу profiles
        prow = await db.fetchone("SELECT gender FROM profiles WHERE user_id=?", (user_id,))
        if prow and prow.get("gender"):
            g = normalize_gender(prow["gender"])
            if g != "none":
                return g
    except Exception:
        pass
    return "none"


async def set_user_gender(user_id: int, gender: str) -> None:
    """Устанавливает пол пользователя в базе данных."""
    norm = normalize_gender(gender)
    val = "Девушка" if norm == "female" else "Парень"
    try:
        await db.execute("UPDATE users SET gender=? WHERE user_id=?", (norm, user_id))
    except Exception:
        pass
    try:
        await db.execute(
            "INSERT INTO profiles (user_id, gender) VALUES (?, ?) "
            "ON CONFLICT(user_id) DO UPDATE SET gender=excluded.gender",
            (user_id, val)
        )
    except Exception:
        pass


async def get_chat_hierarchy(chat_id: int) -> dict[str, Any]:
    """Получает настройки сообщества и иерархии для чата (полная изоляция)."""
    try:
        row = await db.fetchone("SELECT hierarchy FROM chat_themes WHERE chat_id=?", (chat_id,))
        if row and row.get("hierarchy") in COMMUNITY_TYPES:
            return COMMUNITY_TYPES[row["hierarchy"]]
    except Exception:
        pass
    return COMMUNITY_TYPES["default"]


async def set_chat_hierarchy(chat_id: int, hierarchy_id: str, updated_by: int = 0) -> bool:
    """Устанавливает тип сообщества для конкретного чата."""
    if hierarchy_id not in COMMUNITY_TYPES:
        return False
    await db.execute(
        "CREATE TABLE IF NOT EXISTS chat_themes ("
        "chat_id INTEGER PRIMARY KEY, "
        "theme TEXT NOT NULL DEFAULT 'rainbow', "
        "hierarchy TEXT NOT NULL DEFAULT 'default', "
        "gender_mode TEXT NOT NULL DEFAULT 'auto', "
        "updated_at INTEGER NOT NULL DEFAULT 0, "
        "updated_by INTEGER NOT NULL DEFAULT 0)"
    )
    now = int(time.time())
    await db.execute(
        "INSERT INTO chat_themes (chat_id, hierarchy, updated_at, updated_by) VALUES (?, ?, ?, ?) "
        "ON CONFLICT(chat_id) DO UPDATE SET hierarchy=excluded.hierarchy, updated_at=excluded.updated_at, updated_by=excluded.updated_by",
        (chat_id, hierarchy_id, now, updated_by)
    )
    return True


def get_rank_title(rank: int, gender: str = "male", hierarchy_id: str = "default") -> str:
    """Возвращает адаптированное название ранга с учётом пола и типа сообщества."""
    h = COMMUNITY_TYPES.get(hierarchy_id) or COMMUNITY_TYPES["default"]
    g = normalize_gender(gender)
    titles = h["female"] if g == "female" else h["male"]
    return titles.get(rank, f"Ранг {rank}")


def get_rank_plural_title(rank: int, hierarchy_id: str = "default", all_female: bool = False) -> str:
    """Возвращает заголовок группы во множественном числе."""
    h = COMMUNITY_TYPES.get(hierarchy_id) or COMMUNITY_TYPES["default"]
    titles = h["plural_female"] if all_female else h["plural"]
    return titles.get(rank, f"Ранг {rank}")
