FULLWIDTH_MAP = {
    chr(i): chr(i + 0xFEE0) for i in range(0x21, 0x7F)
}

def apply_fancy_font(text: str, font_id: str = "normal") -> str:
    """Преобразует строку в стилизованный Unicode-шрифт."""
    if not text or font_id == "normal":
        return text
    if font_id == "gothic":
        return "".join(GOTHIC_MAP.get(ch, ch) for ch in text)
    if font_id == "double":
        return "".join(DOUBLE_MAP.get(ch, ch) for ch in text)
    if font_id == "script":
        return "".join(SCRIPT_MAP.get(ch, ch) for ch in text)
    if font_id == "fullwidth":
        return "".join(FULLWIDTH_MAP.get(ch, ch) for ch in text)
    return text


async def get_chat_design(chat_id: int) -> dict[str, Any]:
    """Возвращает полный набор параметров оформления чата (полная изоляция)."""
    default_cfg = {
        "theme": "rainbow",
        "hierarchy": "default",
        "border": "classic",
        "crest": "👑",
        "layout": "classic",
        "font": "normal",
        "banner_file_id": None,
        "banner_type": None,
        "gender_mode": "auto"
    }
    try:
        row = await db.fetchone(
            "SELECT theme, hierarchy, border, crest, layout, font, banner_file_id, banner_type, gender_mode "
            "FROM chat_themes WHERE chat_id=?", (chat_id,)
        )
        if row:
            for k in default_cfg:
                if k in row.keys() and row[k] is not None:
                    default_cfg[k] = row[k]
    except Exception:
        pass
    return default_cfg


async def update_chat_design(chat_id: int, updated_by: int = 0, **kwargs) -> bool:
    """Обновляет один или несколько параметров оформления конкретного чата."""
    await db.execute(
        "CREATE TABLE IF NOT EXISTS chat_themes ("
        "chat_id INTEGER PRIMARY KEY, "
        "theme TEXT NOT NULL DEFAULT 'rainbow', "
        "hierarchy TEXT NOT NULL DEFAULT 'default', "
        "border TEXT NOT NULL DEFAULT 'classic', "
        "crest TEXT NOT NULL DEFAULT '👑', "
        "layout TEXT NOT NULL DEFAULT 'classic', "
        "font TEXT NOT NULL DEFAULT 'normal', "
        "gender_mode TEXT NOT NULL DEFAULT 'auto', "
        "banner_file_id TEXT, "
        "banner_type TEXT, "
        "updated_at INTEGER NOT NULL DEFAULT 0, "
        "updated_by INTEGER NOT NULL DEFAULT 0)"
    )
    now = int(time.time())
    # Формируем динамический UPDATE / INSERT
    cur_cfg = await get_chat_design(chat_id)
    cur_cfg.update(kwargs)
    await db.execute(
        "INSERT INTO chat_themes (chat_id, theme, hierarchy, border, crest, layout, font, banner_file_id, banner_type, gender_mode, updated_at, updated_by) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) "
        "ON CONFLICT(chat_id) DO UPDATE SET "
        "theme=excluded.theme, hierarchy=excluded.hierarchy, border=excluded.border, crest=excluded.crest, "
        "layout=excluded.layout, font=excluded.font, banner_file_id=excluded.banner_file_id, banner_type=excluded.banner_type, "
        "gender_mode=excluded.gender_mode, updated_at=excluded.updated_at, updated_by=excluded.updated_by",
        (
            chat_id, cur_cfg["theme"], cur_cfg["hierarchy"], cur_cfg["border"],
            cur_cfg["crest"], cur_cfg["layout"], cur_cfg["font"],
            cur_cfg.get("banner_file_id"), cur_cfg.get("banner_type"), cur_cfg["gender_mode"],
            now, updated_by
        )
    )
    return True
